"""Post‑quantum TLS‑like handshake using liboqs (ML‑KEM‑768).

The client offers suites (one key‑share per suite); the server picks the first suite
in its preference list that the client offers, answers with its own key‑share, and both
sides derive the session key with HKDF‑SHA256 bound to the suite and both hello messages.
Records are encrypted with AES‑256‑GCM and a random nonce per record.

Public API (unchanged):
    state, hello = client_hello()                 # offers CLIENT_SUITES by default
    server_key, suite, reply = server_hello(hello)
    client_key = client_finish(state, reply)

    ch = Channel(server_key)          # or Channel(client_key)
    enc = ch.seal(b"data")
    dec = ch.open(enc)
"""

from __future__ import annotations

import base64
import json
import os
from typing import Dict, Tuple, List, Any

import oqs
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

# --------------------------------------------------------------------------- #
#  Cipher‑suite configuration – only the post‑quantum suite is offered now.   #
# --------------------------------------------------------------------------- #
SERVER_PREFERENCE: List[str] = ["ML-KEM-768-AES256GCM"]
CLIENT_SUITES: List[str] = ["ML-KEM-768-AES256GCM"]

# --------------------------------------------------------------------------- #
#  ML‑KEM‑768 key‑exchange wrapper                                            #
# --------------------------------------------------------------------------- #
class _MLKEM:
    """Key‑exchange implementation based on liboqs ML‑KEM‑768.

    * ``keypair`` returns a tuple ``(secret_key_bytes, public_key_bytes)``.
    * ``respond`` (server side) receives the client’s public key, encapsulates a
      shared secret and returns ``(shared_secret, ciphertext)`` where the ciphertext
      is the server’s key‑share.
    * ``finish`` (client side) receives the client’s secret key and the server’s
      ciphertext and decapsulates the same shared secret.
    """

    _alg = "ML-KEM-768"

    def keypair(self) -> Tuple[bytes, bytes]:
        """Generate a fresh ML‑KEM‑768 key‑pair.

        Returns
        -------
        secret_key : bytes
            Private key that can later be used for decapsulation.
        public_key : bytes
            Public key that is sent to the peer.
        """
        kem = oqs.KeyEncapsulation(self._alg)
        public_key = kem.generate_keypair()          # bytes
        secret_key = kem.export_secret_key()         # bytes
        return secret_key, public_key

    def respond(self, client_share: bytes) -> Tuple[bytes, bytes]:
        """Server side: encapsulate using the client’s public key.

        Parameters
        ----------
        client_share : bytes
            The public key received from the client.

        Returns
        -------
        shared_secret : bytes
            The freshly derived secret (32 bytes for ML‑KEM‑768).
        ciphertext : bytes
            The encapsulated key‑share that the client will decapsulate.
        """
        kem = oqs.KeyEncapsulation(self._alg)
        ciphertext, shared_secret = kem.encap_secret(client_share)
        return shared_secret, ciphertext

    def finish(self, secret_key: bytes, server_share: bytes) -> bytes:
        """Client side: decapsulate using own secret key.

        Parameters
        ----------
        secret_key : bytes
            The private key generated by :meth:`keypair`.
        server_share : bytes
            The ciphertext received from the server.

        Returns
        -------
        shared_secret : bytes
            The same secret derived by the server.
        """
        kem = oqs.KeyEncapsulation(self._alg, secret_key=secret_key)
        return kem.decap_secret(server_share)


# --------------------------------------------------------------------------- #
#  Suite → KEX mapping                                                         #
# --------------------------------------------------------------------------- #
KEX: Dict[str, _MLKEM] = {"ML-KEM-768-AES256GCM": _MLKEM()}


# --------------------------------------------------------------------------- #
#  Session‑key derivation (HKDF‑SHA256)                                         #
# --------------------------------------------------------------------------- #
def _session_key(shared_secret: bytes, suite: str, hello: bytes, reply: bytes) -> bytes:
    """Derive a 32‑byte session key from the shared secret and handshake transcript."""
    info = b"pq-gate suites v1|" + suite.encode() + b"|" + hello + b"|" + reply
    return HKDF(
        algorithm=hashes.SHA256(),
        length=32,
        salt=None,
        info=info,
    ).derive(shared_secret)


# --------------------------------------------------------------------------- #
#  Handshake helpers                                                            #
# --------------------------------------------------------------------------- #
def client_hello(offered: List[str] | None = None) -> Tuple[Dict[str, Any], bytes]:
    """Create a client hello message.

    Parameters
    ----------
    offered : list[str] | None
        List of suite identifiers the client wishes to offer.  If ``None`` the
        default :data:`CLIENT_SUITES` is used.

    Returns
    -------
    state : dict
        Contains the generated secret keys (under ``"secrets"``) and the raw hello
        bytes (under ``"hello"``) for later use by :func:`client_finish`.
    hello : bytes
        JSON‑encoded handshake message to be sent to the server.
    """
    offered = list(offered or CLIENT_SUITES)

    # Validate that every offered suite is known.
    unknown = [s for s in offered if s not in KEX]
    if unknown:
        raise ValueError(f"unknown cipher suite(s) offered: {', '.join(unknown)}")

    secrets_: Dict[str, bytes] = {}
    shares: Dict[str, str] = {}
    for suite in offered:
        secret_key, public_key = KEX[suite].keypair()
        secrets_[suite] = secret_key
        shares[suite] = base64.b64encode(public_key).decode()

    hello = json.dumps({"suites": offered, "shares": shares}).encode()
    return {"secrets": secrets_, "hello": hello}, hello


def server_hello(hello: bytes) -> Tuple[bytes, str, bytes]:
    """Process a client hello and produce a server hello.

    Parameters
    ----------
    hello : bytes
        The client hello produced by :func:`client_hello`.

    Returns
    -------
    session_key : bytes
        The derived session key (32 bytes).
    suite : str
        The suite selected for the connection.
    reply : bytes
        JSON‑encoded server hello to be sent back to the client.

    Raises
    ------
    ValueError
        If no common suite can be negotiated.
    """
    msg = json.loads(hello)

    # Find the first suite that both sides support.
    suite = next(
        (s for s in SERVER_PREFERENCE if s in msg.get("suites", []) and s in msg.get("shares", {})),
        None,
    )
    if suite is None:
        raise ValueError("no common cipher suite")

    if suite not in KEX:
        # Defensive programming – should never happen with the current configuration.
        raise ValueError(f"unsupported suite selected by server: {suite}")

    client_share = base64.b64decode(msg["shares"][suite])
    shared, server_share = KEX[suite].respond(client_share)

    reply = json.dumps(
        {"suite": suite, "share": base64.b64encode(server_share).decode()}
    ).encode()
    return _session_key(shared, suite, hello, reply), suite, reply


def client_finish(state: Dict[str, Any], reply: bytes) -> bytes:
    """Complete the handshake on the client side.

    Parameters
    ----------
    state : dict
        The state object returned by :func:`client_hello`.
    reply : bytes
        The server hello received from :func:`server_hello`.

    Returns
    -------
    session_key : bytes
        The derived session key (32 bytes).

    Raises
    ------
    ValueError
        If the server selected a suite that was not offered by the client.
    """
    msg = json.loads(reply)
    suite = msg["suite"]
    if suite not in state["secrets"]:
        raise ValueError("server chose a suite we did not offer")
    server_share = base64.b64decode(msg["share"])
    shared = KEX[suite].finish(state["secrets"][suite], server_share)
    return _session_key(shared, suite, state["hello"], reply)


# --------------------------------------------------------------------------- #
#  Secure channel (AES‑256‑GCM)                                                #
# --------------------------------------------------------------------------- #
class Channel:
    """Encrypt/decrypt records with AES‑256‑GCM under the derived session key."""

    def __init__(self, session_key: bytes):
        if len(session_key) != 32:
            raise ValueError("session_key must be 32 bytes for AES‑256‑GCM")
        self._aead = AESGCM(session_key)

    def seal(self, plaintext: bytes) -> bytes:
        """Encrypt ``plaintext`` and prepend a fresh 12‑byte nonce.

        Returns
        -------
        bytes
            ``nonce || ciphertext || tag`` as produced by :class:`AESGCM`.
        """
        nonce = os.urandom(12)
        return nonce + self._aead.encrypt(nonce, plaintext, None)

    def open(self, record: bytes) -> bytes:
        """Decrypt a record produced by :meth:`seal`.

        Parameters
        ----------
        record : bytes
            The data returned by :meth:`seal`.

        Returns
        -------
        bytes
            The original plaintext.

        Raises
        ------
        cryptography.exceptions.InvalidTag
            If authentication fails.
        """
        if len(record) < 12:
            raise ValueError("record is too short to contain a nonce")
        nonce, ciphertext = record[:12], record[12:]
        return self._aead.decrypt(nonce, ciphertext, None)


