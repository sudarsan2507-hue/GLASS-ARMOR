"""Signed webhooks (ML‑DSA‑65), Stripe‑style signature header.

The sender signs "<timestamp>.<body>" and sends the header
    X-Signature: t=<unix time>,v1=<base64 signature>
The receiver keeps one public key per signature scheme (dict scheme -> key), checks the
signature for its scheme and rejects messages older than `tolerance` seconds (replay window).

The implementation now uses post‑quantum signatures from liboqs (ML‑DSA‑65) while
preserving the original public API (`generate_keypair`, `sign_webhook`,
`verify_webhook`). Keys are exported/imported as PEM‑like blobs so existing
tests that treat them as PEM continue to work.
"""
import base64
import time
from typing import Tuple, Dict

import oqs
from cryptography.exceptions import InvalidSignature  # kept for API compatibility


SCHEME = "v1"
_OQS_ALG = "ML-DSA-65"


def _pem_wrap(data: bytes, kind: str) -> bytes:
    """Wrap raw key bytes in a PEM‑like container.

    Args:
        data: Raw key bytes.
        kind: Either ``PUBLIC KEY`` or ``PRIVATE KEY``.

    Returns:
        PEM‑encoded bytes.
    """
    b64 = base64.b64encode(data).decode()
    lines = [f"-----BEGIN {kind}-----"]
    # split into 64‑character lines as PEM does
    lines += [b64[i : i + 64] for i in range(0, len(b64), 64)]
    lines.append(f"-----END {kind}-----\n")
    return "\n".join(lines).encode()


def _pem_unwrap(pem: bytes, kind: str) -> bytes:
    """Extract raw key bytes from a PEM‑like container.

    Args:
        pem: PEM‑encoded bytes.
        kind: Expected container type (``PUBLIC KEY`` or ``PRIVATE KEY``).

    Returns:
        Raw key bytes.

    Raises:
        ValueError: If the PEM header/footer are missing or malformed.
    """
    header = f"-----BEGIN {kind}-----".encode()
    footer = f"-----END {kind}-----".encode()
    if not (pem.strip().startswith(header) and pem.strip().endswith(footer)):
        raise ValueError(f"Invalid PEM format for {kind}")

    # Remove header/footer and any whitespace/newlines
    b64 = pem.strip()[len(header) : -len(footer)].replace(b"\n", b"").replace(b"\r", b"")
    return base64.b64decode(b64)


def generate_keypair() -> Tuple[bytes, bytes]:
    """Return ``(public_key, private_key)`` as PEM‑like bytes for the webhook sender.

    The keys are generated with ML‑DSA‑65 (post‑quantum) and wrapped in PEM
    containers so existing code that expects PEM continues to work.
    """
    sig = oqs.Signature(_OQS_ALG)
    public_raw = sig.generate_keypair()          # bytes
    private_raw = sig.export_secret_key()        # bytes
    public_pem = _pem_wrap(public_raw, "PUBLIC KEY")
    private_pem = _pem_wrap(private_raw, "PRIVATE KEY")
    return public_pem, private_pem


def sign_webhook(private_key: bytes, body: bytes, timestamp: int | None = None) -> str:
    """Return the ``X‑Signature`` header value for ``body`` (bytes).

    Args:
        private_key: PEM‑encoded private key generated by :func:`generate_keypair`.
        body: The HTTP request body (bytes) to be signed.
        timestamp: Optional Unix timestamp; if omitted the current time is used.

    Returns:
        Header string in the form ``t=<ts>,v1=<base64‑sig>``.
    """
    ts = int(time.time() if timestamp is None else timestamp)
    # Load raw secret key from PEM
    secret_raw = _pem_unwrap(private_key, "PRIVATE KEY")
    signer = oqs.Signature(_OQS_ALG, secret_key=secret_raw)
    message = str(ts).encode() + b"." + body
    signature = signer.sign(message)                     # bytes
    b64_sig = base64.b64encode(signature).decode()
    return f"t={ts},{SCHEME}={b64_sig}"


def _parse(header: str) -> Dict[str, str]:
    """Parse a Stripe‑style signature header into a dict."""
    fields: Dict[str, str] = {}
    for part in header.split(","):
        name, _, value = part.partition("=")
        fields[name.strip()] = value.strip()
    return fields


def verify_webhook(
    keys: Dict[str, bytes],
    body: bytes,
    header: str,
    now: float | None = None,
    tolerance: int = 300,
) -> bool:
    """Validate a webhook signature.

    Args:
        keys: Mapping ``scheme -> public_key`` where the public key is PEM‑encoded.
        body: The HTTP request body (bytes) that was signed.
        header: The raw ``X‑Signature`` header value.
        now: Optional current time (float). If omitted ``time.time()`` is used.
        tolerance: Maximum allowed age (seconds) for the timestamp.

    Returns:
        ``True`` if the signature is valid and the timestamp is within the
        allowed window, otherwise ``False``.
    """
    try:
        fields = _parse(header)
        ts = int(fields["t"])
        b64_sig = fields[SCHEME]
        signature = base64.b64decode(b64_sig)

        # Load the PEM‑encoded public key for the expected scheme
        public_pem = keys[SCHEME]
        public_raw = _pem_unwrap(public_pem, "PUBLIC KEY")

        verifier = oqs.Signature(_OQS_ALG)
        message = str(ts).encode() + b"." + body
        ok = verifier.verify(message, signature, public_raw)
        if not ok:
            raise InvalidSignature  # unify error handling with the old API
    except (KeyError, ValueError, InvalidSignature):
        return False

    now_val = time.time() if now is None else now
    return abs(now_val - ts) <= tolerance
