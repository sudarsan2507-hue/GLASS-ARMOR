"""Post‑quantum envelope encryption using liboqs (ML‑KEM‑768).

Each file is encrypted with a fresh random AES‑256‑GCM data key. The data key
is derived from a KEM encapsulation (ML‑KEM‑768) and the encapsulated ciphertext
is stored next to the encrypted payload. The filename is bound to the ciphertext
as associated data.

Blob layout:
    2‑byte encapsulated‑key length | encapsulated key | 12‑byte nonce | ciphertext
"""

import os
import struct

import oqs
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# --------------------------------------------------------------------------- #
# Key‑pair handling (ML‑KEM‑768)
# --------------------------------------------------------------------------- #
def generate_keypair():
    """Return (public_key, private_key) as raw bytes for a file owner.

    The keys are generated with liboqs using the ML‑KEM‑768 algorithm.
    """
    kem = oqs.KeyEncapsulation("ML-KEM-768")
    public_key = kem.generate_keypair()          # bytes
    private_key = kem.export_secret_key()        # bytes
    return public_key, private_key


# --------------------------------------------------------------------------- #
# KEM‑based key wrap / unwrap (kept for API compatibility)
# --------------------------------------------------------------------------- #
def wrap_key(public_key, data_key=None):
    """Encapsulate a fresh symmetric key for the owner of ``public_key``.

    The original RSA‑OAEP API allowed the caller to supply an arbitrary
    ``data_key``. With ML‑KEM the symmetric key is generated by the KEM
    itself, so the ``data_key`` argument is ignored. The function returns the
    encapsulated ciphertext (the "wrapped" key) which can later be decapsulated
    with :func:`unwrap_key` to recover the same symmetric key.
    """
    # ``data_key`` is ignored – the KEM decides the secret.
    _, shared_secret = oqs.KeyEncapsulation("ML-KEM-768").encap_secret(public_key)
    # The encapsulated ciphertext is the wrapped key.
    # ``encap_secret`` returns (ciphertext, shared_secret); we need the ciphertext.
    # To obtain the ciphertext we must perform the encapsulation again, this time
    # keeping the ciphertext.
    ciphertext, _ = oqs.KeyEncapsulation("ML-KEM-768").encap_secret(public_key)
    return ciphertext


def unwrap_key(private_key, wrapped):
    """Decapsulate ``wrapped`` with ``private_key`` and return the symmetric key.

    The returned key is a 32‑byte value suitable for AES‑256‑GCM.
    """
    kem = oqs.KeyEncapsulation("ML-KEM-768", secret_key=private_key)
    return kem.decap_secret(wrapped)


# --------------------------------------------------------------------------- #
# Envelope encryption helpers
# --------------------------------------------------------------------------- #
def encrypt_file(public_key, plaintext, filename=""):
    """Encrypt ``plaintext`` for the owner of ``public_key``.

    A fresh AES‑256‑GCM data key is derived from a KEM encapsulation. The
    encapsulated ciphertext (the wrapped key) is stored together with the
    AES‑GCM nonce and the ciphertext.
    """
    # Perform KEM encapsulation: obtain wrapped key and the symmetric data key.
    wrapped_key, data_key = oqs.KeyEncapsulation("ML-KEM-768").encap_secret(public_key)

    # AES‑GCM encryption of the payload.
    nonce = os.urandom(12)
    aesgcm = AESGCM(data_key)                     # data_key is 32 bytes → AES‑256
    ciphertext = aesgcm.encrypt(nonce, plaintext, filename.encode())

    # Blob layout: length (2 bytes) | wrapped key | nonce (12 bytes) | ciphertext
    return struct.pack(">H", len(wrapped_key)) + wrapped_key + nonce + ciphertext


def decrypt_file(private_key, blob, filename=""):
    """Decrypt a blob produced by :func:`encrypt_file`.

    Raises if the key, blob or filename is wrong.
    """
    # Extract components from the blob.
    (wrapped_len,) = struct.unpack(">H", blob[:2])
    wrapped_key = blob[2 : 2 + wrapped_len]
    nonce = blob[2 + wrapped_len : 14 + wrapped_len]
    ciphertext = blob[14 + wrapped_len :]

    # Recover the symmetric data key via KEM decapsulation.
    data_key = unwrap_key(private_key, wrapped_key)

    # Decrypt the payload.
    aesgcm = AESGCM(data_key)
    return aesgcm.decrypt(nonce, ciphertext, filename.encode())


# --------------------------------------------------------------------------- #
# Convenience I/O helpers (filename bound as associated data)
# --------------------------------------------------------------------------- #
def save_encrypted(path, public_key, plaintext):
    """Encrypt ``plaintext`` and write it to ``path`` (filename bound as AD)."""
    blob = encrypt_file(public_key, plaintext, os.path.basename(path))
    with open(path, "wb") as f:
        f.write(blob)


def load_encrypted(path, private_key):
    """Read and decrypt a file written by :func:`save_encrypted`."""
    with open(path, "rb") as f:
        blob = f.read()
    return decrypt_file(private_key, blob, os.path.basename(path))
