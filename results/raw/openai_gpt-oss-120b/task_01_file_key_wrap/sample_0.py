"""Post‑quantum envelope encryption using liboqs (ML‑KEM‑768).

Each file is encrypted with a fresh random AES‑256‑GCM data key that is
derived from a KEM encapsulation. The encapsulated ciphertext (the
“wrapped key”) is stored next to the AES ciphertext. The filename is bound
to the ciphertext as associated data.

Blob layout:
    2‑byte wrapped‑key length | wrapped key | 12‑byte nonce | ciphertext
"""

import os
import struct

import oqs
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# --------------------------------------------------------------------------- #
# Key‑pair handling (ML‑KEM‑768)
# --------------------------------------------------------------------------- #
def generate_keypair():
    """Generate a ML‑KEM‑768 key‑pair.

    Returns
    -------
    (public_key, secret_key) : tuple[bytes, bytes]
        * ``public_key`` – bytes that can be shared with the encryptor.
        * ``secret_key`` – private key bytes that must be kept secret.
    """
    kem = oqs.KeyEncapsulation("ML-KEM-768")
    public_key = kem.generate_keypair()
    secret_key = kem.export_secret_key()
    return public_key, secret_key


# --------------------------------------------------------------------------- #
# Wrapping / unwrapping (KEM encapsulation)
# --------------------------------------------------------------------------- #
def wrap_key(public_key, _unused_data_key=None):
    """Encapsulate a fresh shared secret for ``public_key``.

    The function signature is kept for compatibility with the original
    RSA‑OAEP implementation; the ``data_key`` argument is ignored because
    the shared secret is generated by the KEM itself.

    Returns
    -------
    wrapped_key : bytes
        The encapsulated ciphertext that can be stored alongside the file.
    """
    kem = oqs.KeyEncapsulation("ML-KEM-768")
    wrapped_key, _shared_secret = kem.encap_secret(public_key)
    return wrapped_key


def unwrap_key(secret_key, wrapped):
    """Decapsulate ``wrapped`` using the owner's ``secret_key``.

    Returns
    -------
    data_key : bytes
        The 32‑byte shared secret that will be used as the AES‑256‑GCM key.
    """
    kem = oqs.KeyEncapsulation("ML-KEM-768", secret_key=secret_key)
    data_key = kem.decap_secret(wrapped)
    return data_key


# --------------------------------------------------------------------------- #
# File encryption / decryption
# --------------------------------------------------------------------------- #
def encrypt_file(public_key, plaintext, filename=""):
    """Encrypt ``plaintext`` for the owner of ``public_key``.

    A fresh AES‑256‑GCM key is derived from a KEM encapsulation. The filename
    (or any caller‑provided string) is bound as associated data.

    Returns
    -------
    blob : bytes
        The envelope‑encrypted blob (see layout description above).
    """
    # 1️⃣  Encapsulate a shared secret – this becomes the AES data key.
    kem = oqs.KeyEncapsulation("ML-KEM-768")
    wrapped_key, data_key = kem.encap_secret(public_key)

    # 2️⃣  Encrypt the payload with AES‑256‑GCM.
    nonce = os.urandom(12)
    ciphertext = AESGCM(data_key).encrypt(nonce, plaintext, filename.encode())

    # 3️⃣  Assemble the final blob.
    return struct.pack(">H", len(wrapped_key)) + wrapped_key + nonce + ciphertext


def decrypt_file(secret_key, blob, filename=""):
    """Decrypt a blob produced by :func:`encrypt_file`.

    Raises
    ------
    Exception
        If decryption fails (e.g., wrong key, corrupted blob, or mismatched
        associated data).
    """
    # Extract components according to the layout.
    (wrapped_len,) = struct.unpack(">H", blob[:2])
    wrapped = blob[2 : 2 + wrapped_len]
    nonce = blob[2 + wrapped_len : 14 + wrapped_len]
    ciphertext = blob[14 + wrapped_len :]

    # Recover the AES data key via KEM decapsulation.
    data_key = unwrap_key(secret_key, wrapped)

    # Decrypt the payload.
    return AESGCM(data_key).decrypt(nonce, ciphertext, filename.encode())


# --------------------------------------------------------------------------- #
# Convenience helpers for file I/O
# --------------------------------------------------------------------------- #
def save_encrypted(path, public_key, plaintext):
    """Encrypt ``plaintext`` and write the envelope blob to ``path``.

    The file name (basename of ``path``) is bound as associated data.
    """
    blob = encrypt_file(public_key, plaintext, os.path.basename(path))
    with open(path, "wb") as f:
        f.write(blob)


def load_encrypted(path, secret_key):
    """Read an envelope‑encrypted file and return the decrypted plaintext."""
    with open(path, "rb") as f:
        blob = f.read()
    return decrypt_file(secret_key, blob, os.path.basename(path))
